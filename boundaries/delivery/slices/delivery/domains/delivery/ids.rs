#[derive(Clone, Debug, Eq, Hash, PartialEq)]
pub struct DeliveryId(String);

impl DeliveryId {
    #[must_use]
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

